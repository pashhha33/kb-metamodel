/**
 * Набор свойств, активируемых назначенными категориями (12-й тип M1, реализует требование R-TRIGGER). Активация включает потомков категории. Нормативный источник: ADR-0008 §3.1…§3.3; docs/metamodel/00_overview.md §7.3.
 */

export type Aspect = SystemContract & {
  type: 'aspect';
  /**
   * Ключ аспекта: EN snake_case (literary_person, ai_generated_media).
   */
  title?: string;
  /**
   * Подпись аспекта: «Литературная деятельность», «Генерация ИИ».
   */
  label: string;
  /**
   * Слой определения. Нормативно для Aspect — system (ADR-0008 §3.1, §3.7). Поле необязательное: обязательность layer закреплена только за ObjectType (00_overview §5, NAME_MAPPING §2), а вопрос о распространении layer на все определения M1 отложен в фазу 3c (находка F-3.3). До выпуска 0.14.0 поле отсутствовало во фрагменте, и пример ADR-0008 §3.1 отклонялся схемой — находка F-3.20.
   */
  layer?: 'system' | 'domain';
  /**
   * Категории, при назначении которых объект получает свойства аспекта, кардинальность 1..n. Аспект активируется, если назначена сама категория из списка или любой её потомок (обход parent вниз).
   *
   * @minItems 1
   */
  trigger_categories: [string, ...string[]];
  /**
   * Плоский упорядоченный список активируемых свойств, кардинальность 1..n. Значения хранятся в плоском frontmatter самого объекта: отдельный объект-«профиль» не создаётся.
   *
   * @minItems 1
   */
  properties: [string, ...string[]];
  /**
   * Ужесточения ограничений для свойств в контексте аспекта. Порядок применения аспектов — по возрастанию id (детерминированно, ADR-0008 §3.3 п.6b).
   */
  property_overrides?: PropertyOverride[];
  /**
   * Выключенный аспект не активируется; позволяет временно отключить набор без удаления.
   */
  is_active: boolean;
  description?: string;
  /**
   * Жизненный цикл модельных сущностей (Спецификация §16).
   */
  lifecycle?: 'experimental' | 'standard' | 'deprecated' | 'archived';
  /**
   * ЗАДЕЛ (в MVP не используется): расширение триггера на тип отношения. Семантика «ИЛИ» относительно trigger_categories (ADR-0008 §3.6).
   */
  trigger_relation_types?: string[];
  /**
   * ЗАДЕЛ (в MVP не используется): триггер по значению свойства.
   */
  trigger_conditions?: string[];
  /**
   * ЗАДЕЛ (в MVP не используется): триггер по типу объекта.
   */
  trigger_types?: string[];
};

/**
 * Системный контракт объекта: поля, которые есть у каждого объекта M0 и M1. Задаются ядром (M2) и не могут быть переопределены как обычные свойства. Нормативный источник: docs/metamodel/00_overview.md §2.
 */

export interface PropertyOverride {
  /**
   * Ссылка Obsidian вида [[Цель]] или [[Цель|Подпись]]. Каноническая форма — [[{title} ({PREFIX}-{id})|{title}]]; стабильная часть (PREFIX-ULID) обязательна по link.r4, но на уровне схемы не требуется, чтобы не отклонять исторические и рукописные ссылки.
   */
  property: string;
  /**
   * Допустимо только false → true (inherit.r3).
   */
  required?: boolean;
  /**
   * Допустимо только сужение: 0..n → 1..n, 0..1 → 1 (inherit.r4).
   */
  cardinality?: '0..1' | '1' | '0..n' | '1..n';
  /**
   * Сужение перечня допустимых значений.
   */
  allowed_values?: string[];
  /**
   * Сужение набора допустимых типов цели.
   */
  target_types?: string[];
  /**
   * Изменение смысла унаследованного свойства запрещено (inherit.r1): поле не допускается в переопределении.
   */
  definition?: {
    [k: string]: any;
  };
  /**
   * Изменение типа значения запрещено (inherit.r2): поле не допускается в переопределении.
   */
  value_type?: {
    [k: string]: any;
  };
}

/**
 * Автоматизация и форма создания объекта (M1). Форма создания выводится из типа объекта: отдельный тип Form отклонён как дублирование данных (ADR-0010 §3.4). Нормативный источник: docs/metamodel/00_overview.md §3; ADR-0010 §2.4, §3.3, §3.4.
 */

export type Automation = SystemContract & {
  type: 'automation';
  /**
   * Ключ автоматизации: EN snake_case (create_chapter).
   */
  title?: string;
  /**
   * Подпись автоматизации: «Создать главу».
   */
  label: string;
  /**
   * manual, on_create, on_update, scheduled. Абстрактный идентификатор без названий инструментов (D-0057).
   */
  trigger: 'manual' | 'on_create' | 'on_update' | 'scheduled';
  /**
   * Механизм выполнения автоматизации.
   */
  mechanism: 'bases' | 'table' | 'card' | 'kanban' | 'graph' | 'query' | 'custom';
  /**
   * Типы объектов, к которым применяется автоматизация.
   */
  target_types?: string[];
  /**
   * Необязательное сужение и порядок полей формы создания. Пусто — выводятся все обязательные. Поля системного контракта адресуются как sys:title, sys:status и т.д., поскольку title — системный атрибут, а не объект Property (ADR-0010 §3.3).
   */
  form_fields?: string[];
  /**
   * Значения по умолчанию для полей формы. Поддерживаются служебные плейсхолдеры {next_sequence}, {parent}, {today} (ADR-0010 §2.2, §3.3).
   */
  defaults?: {
    [k: string]: string | number | boolean | null | (string | number | boolean | null)[];
  };
  /**
   * Задел: подтверждение перед созданием. По умолчанию true — файл не появляется без явного подтверждения (принцип S6, Q-36 = A). В MVP не используется: всегда подтверждение.
   */
  require_confirmation?: boolean;
  /**
   * Выключенная автоматизация сохраняется, но не применяется.
   */
  is_active: boolean;
  description?: string;
  /**
   * Жизненный цикл модельных сущностей (Спецификация §16).
   */
  lifecycle?: 'experimental' | 'standard' | 'deprecated' | 'archived';
};

