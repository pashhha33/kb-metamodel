/**
 * Системный контракт объекта: поля, которые есть у каждого объекта M0 и M1. Задаются ядром (M2) и не могут быть переопределены как обычные свойства. Нормативный источник: docs/metamodel/00_overview.md §2.
 */

export interface SystemContract {
  /**
   * Единственный носитель идентичности. Не меняется никогда, не переиспользуется (ADR-0002).
   */
  id: string;
  /**
   * Идентификатор типа объекта, snake_case. Строка, а не wikilink: осознанная потеря рёбер «экземпляр → тип» в графе (ADR-0005).
   */
  type: string;
  /**
   * Единственный источник отображаемого названия. Одинаковые title у разных объектов допустимы.
   */
  title: string;
  /**
   * Только реальные псевдонимы; порядок не значим. Правило aliases[0] = title отменено (ADR-0004).
   */
  aliases?: string[];
  /**
   * Дата создания объекта.
   */
  created_at: string;
  /**
   * Дата последнего изменения.
   */
  updated_at: string;
  /**
   * Стадия жизненного цикла данных.
   */
  status: 'capture' | 'draft' | 'normalizing' | 'active' | 'archived' | 'deleted';
  /**
   * Свободные метки Obsidian. Не валидируются семантически (00_overview §2).
   */
  tags?: string[];
  /**
   * Назначения категорий одной оси классификации: cat_<facet_key> (ADR-0007). Расширяемый системный слой: состав полей порождается определениями Facet.
   *
   * This interface was referenced by `SystemContract`'s JSON-Schema definition
   * via the `patternProperty` "^cat_[a-z][a-z0-9_]{1,30}$".
   */
  [k: string]: string[];
}

